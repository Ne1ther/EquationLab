const PLAN='equationlab.document-numbering-plan.v1';
const DEFAULT='EquationLabNumberFormat';
const FORMAT={1:'ARABIC',A:'ALPHABETIC',a:'alphabetic',I:'ROMAN',i:'roman'};
const COUNTER={EquationLab:'E',ELChapter:'C',ELSection:'S',MTEqn:'E',MTChap:'C',MTSec:'S'};
const NAME={E:'EquationLab',C:'ELChapter',S:'ELSection'};
const SHARED_NAME={E:'MTEqn',C:'MTChap',S:'MTSec'};
const serializer=new XMLSerializer();
const canonical=value=>Array.isArray(value)?value.map(canonical):value&&typeof value==='object'?Object.fromEntries(Object.keys(value).sort().map(key=>[key,canonical(value[key])])):value;
const stable=value=>JSON.stringify(canonical(value));
function plain(value,label){if(!value||typeof value!=='object'||Array.isArray(value)||![Object.prototype,null].includes(Object.getPrototypeOf(value)))throw Error('Invalid '+label);return value;}
function keys(value,allowed,label){plain(value,label);for(const key of Object.keys(value))if(!allowed.includes(key))throw Error(`Unknown ${label} property: ${key}`);}
const children=node=>Array.from(node.childNodes??[]).filter(n=>n.nodeType===1);
const descendants=(node,name)=>Array.from(node.getElementsByTagNameNS(NS.w,name));
const isLocked=node=>node.hasAttributeNS(NS.w,'fldLock')&&!['0','false','off'].includes(node.getAttributeNS(NS.w,'fldLock').toLowerCase());

function tokens(pattern){
 previewNumberFormat(pattern);let end=0;const result=[];
 for(const match of pattern.matchAll(/#([CSE])([1AaIi])/g)){
  if(match.index>end)result.push({text:pattern.slice(end,match.index)});
  result.push({counter:match[1],format:match[2]});end=match.index+match[0].length;
 }
 if(end<pattern.length)result.push({text:pattern.slice(end)});return result;
}
function numeric(text,format){
 const value=text.trim();let n;
 if(format==='ARABIC')n=/^[1-9]\d*$/.test(value)?Number(value):NaN;
 else if(['ALPHABETIC','alphabetic'].includes(format)){
  const upper=format==='ALPHABETIC';n=(upper?/^([A-Z])\1*$/:/^([a-z])\1*$/).test(value)?(value.length-1)*26+value.charCodeAt(0)-(upper?64:96):NaN;
 }else if(['ROMAN','roman'].includes(format)){
  const letters={I:1,V:5,X:10,L:50,C:100,D:500,M:1000},v=value.toUpperCase();n=0;
  for(let i=0;i<v.length;i++){if(!letters[v[i]]){n=NaN;break;}n+=letters[v[i]]<(letters[v[i+1]]??0)?-letters[v[i]]:letters[v[i]];}
 }else n=NaN;
 if(!Number.isSafeInteger(n)||n<1||n>32767)throw Error('Number cache is unavailable or cannot be interpreted safely');
 const code=Object.keys(FORMAT).find(key=>FORMAT[key]===format);
 if(previewNumberFormat('#E'+code,{equation:n})!==value)throw Error('Number cache does not match its declared numeric format');
 return n;
}
function sequence(code,cached){
 const match=/^\s*SEQ\s+(EquationLab|ELChapter|ELSection|MTEqn|MTChap|MTSec)\b([\s\S]*)$/i.exec(code);
 if(!match)throw Error('The number contains an unknown field');
 const name=Object.keys(COUNTER).find(key=>key.toLowerCase()===match[1].toLowerCase()),parts=match[2].match(/\S+/g)??[];
 let format='ARABIC',mode=null,numericFormats=0;
 for(let i=0;i<parts.length;i++){
  const token=parts[i];
  if(['\\n','\\c'].includes(token)){if(mode)throw Error('Ambiguous sequence counter switches');mode=token;}
  else if(token==='\\r'){if(mode||!/^\d+$/.test(parts[i+1]??'')||Number(parts[i+1])<0||Number(parts[i+1])>32767)throw Error('Invalid sequence reset');mode=token;i++;}
  else if(token==='\\h')throw Error('Hidden counter fields require a Word host operation');
  else if(token==='\\*'){
   const next=parts[++i];if(Object.values(FORMAT).includes(next)){format=next;if(++numericFormats>1)throw Error('Ambiguous numeric format');}
   else if(!['MERGEFORMAT','CHARFORMAT'].includes(next))throw Error('Unknown sequence formatting switch');
  }else throw Error('Unknown sequence switch');
 }
 return {name,counter:COUNTER[name],code,format,value:numeric(cached,format),changesCounter:mode!=='\\c'};
}

// Read only the number's bounded bookmark range. An enclosing paragraph,
// object run or external bookmark is never regenerated by this formatter.
function prepare(object,pattern){
 if(object.parseError||!object.nativeSha256)throw Error('Unsupported native equation');
 if(!object.mainDocument)throw Error('Only main-document equation numbers are supported');
 if(!object.layout?.owned||!object.layout.bookmarkName||!object.layout.numberFormat)throw Error('Unnumbered or legacy equations require a Word host operation');
 const run=object.element.parentNode?.parentNode,p=run?.parentNode;
 if(run?.namespaceURI!==NS.w||run.localName!=='r'||p?.namespaceURI!==NS.w||p.localName!=='p')throw Error('Unsupported equation wrapper');
 if(p.getElementsByTagNameNS(NS.o,'OLEObject').length!==1)throw Error('Several equations share this paragraph');
 for(let n=p;n;n=n.parentNode)if(n.namespaceURI===NS.w&&['ins','del','moveFrom','moveTo','sdt'].includes(n.localName))throw Error('Tracked or content-controlled numbering requires Word');
 if(['ins','del','moveFrom','moveTo','sdt','pPrChange','rPrChange','sectPr','numPr'].some(tag=>descendants(p,tag).length))throw Error('Tracked or special paragraph content requires Word');
 const starts=descendants(p,'bookmarkStart');
 if(starts.length!==1||starts[0].getAttributeNS(NS.w,'name')!==object.layout.bookmarkName)throw Error('Custom or overlapping bookmarks require Word');
 const start=starts[0],id=start.getAttributeNS(NS.w,'id'),ends=descendants(p,'bookmarkEnd');
 if(start.parentNode!==p||ends.length!==1||ends[0].parentNode!==p||ends[0].getAttributeNS(NS.w,'id')!==id)throw Error('The numbering bookmark is not a complete paragraph-local range');
 const end=ends[0],nodes=[];let n=start.nextSibling;
 for(;n&&n!==end;n=n.nextSibling)nodes.push(n);
 if(n!==end)throw Error('The numbering bookmark is reversed');
 const shared=object.layout.numberingFamily==='mathtype',envelope=shared?sharedNumberRangeNodes(object,p,scanWordNumberingPart(object.partDoc,object.part)):new Set();
 const region=new Set(nodes);
 for(const node of children(p)){
  if(envelope.has(node))continue;
  if(region.has(node)||node===start||node===end||node===run||node.localName==='pPr')continue;
  if(node.namespaceURI!==NS.w||node.localName!=='r'||children(node).some(c=>!['rPr','tab','t'].includes(c.localName)||c.namespaceURI!==NS.w)||descendants(node,'t').some(t=>t.textContent.trim()))throw Error('Equation and prose or custom content share the paragraph');
 }
 if(children(run).some(n=>n.namespaceURI!==NS.w||!['rPr','object'].includes(n.localName)))throw Error('Equation and prose share the same run');
 const fields=[],styles=[];let current=null;
 const textStyle=node=>{const r=node.parentNode,props=children(r).find(n=>n.namespaceURI===NS.w&&n.localName==='rPr');styles.push(props?serializer.serializeToString(props):'');};
 const visit=(node,inSimple=false)=>{
  if(node.nodeType!==1){if(node.nodeType===3&&node.textContent.trim())throw Error('Unexpected number content');return;}
  if(node.namespaceURI!==NS.w||!['r','rPr','t','fldSimple','fldChar','instrText'].includes(node.localName))throw Error('Unsupported number content');
  if(isLocked(node))throw Error('The numbering field is locked');
  if(node.localName==='rPr')return;
  if(node.localName==='fldSimple'){
   if(current||inSimple)throw Error('Nested number fields require Word');
   const f={code:node.getAttributeNS(NS.w,'instr'),text:'',mode:'result'};current=f;
   for(const child of Array.from(node.childNodes))visit(child,true);
   fields.push(sequence(f.code,f.text));current=null;return;
  }
  if(node.localName==='fldChar'){
   if(inSimple)throw Error('Nested number fields require Word');
   const kind=node.getAttributeNS(NS.w,'fldCharType');
   if(kind==='begin'){if(current)throw Error('Nested number fields require Word');current={code:'',text:'',mode:'code'};}
   else if(kind==='separate'){if(!current||current.mode!=='code')throw Error('Malformed number field');current.mode='result';}
   else if(kind==='end'){if(!current||current.mode!=='result')throw Error('Malformed number field');fields.push(sequence(current.code,current.text));current=null;}
   else throw Error('Unknown field delimiter');return;
  }
  if(node.localName==='instrText'){
   if(shared&&current?.mode!=='code'){if(current)current.text+=node.textContent;textStyle(node);return;}
   if(!current||current.mode!=='code')throw Error('Unbound number instruction');current.code+=node.textContent;return;
  }
  if(node.localName==='t'){if(current?.mode==='code')throw Error('Malformed number field');if(current)current.text+=node.textContent;textStyle(node);return;}
  for(const child of Array.from(node.childNodes))visit(child,inSimple);
 };
 for(const node of nodes)visit(node);
 if(current)throw Error('Unclosed number field');
 if(new Set(styles).size>1)throw Error('Mixed character formatting inside the number requires Word');
 if(fields.filter(f=>f.counter==='E').length!==1||new Set(fields.map(f=>f.counter)).size!==fields.length)throw Error('Ambiguous sequence fields');
 const wanted=tokens(pattern),byCounter=new Map(fields.map(f=>[f.counter,f]));
 for(const field of fields)if(field.changesCounter&&!wanted.some(t=>t.counter===field.counter))throw Error('Removing this counter would change its reset or sequence behaviour');
 const values={E:byCounter.get('E').value,C:byCounter.get('C')?.value??object.layout.chapter,S:byCounter.get('S')?.value??object.layout.section};
 for(const token of wanted)if(token.counter&&(!Number.isSafeInteger(values[token.counter])||values[token.counter]<1||values[token.counter]>32767))throw Error('Chapter or section context has not been established');
 const numberText=previewNumberFormat(pattern,{chapter:values.C??1,section:values.S??1,equation:values.E});
 const doc=p.ownerDocument,rPr=styles[0]?parseDocxXml(`<w:root xmlns:w="${NS.w}">${styles[0]}</w:root>`).documentElement.firstChild:null;
 const textRun=text=>{const r=doc.createElementNS(NS.w,'w:r');if(rPr)r.appendChild(doc.importNode(rPr,true));const t=doc.createElementNS(NS.w,shared?'w:instrText':'w:t');t.setAttribute('xml:space','preserve');t.appendChild(doc.createTextNode(text));r.appendChild(t);return r;};
 const replacements=wanted.map(token=>{
  if(token.text!==undefined)return textRun(token.text);
  const old=byCounter.get(token.counter),base=old?.code??`SEQ ${(shared?SHARED_NAME:NAME)[token.counter]} \\c`;
  const code=base.replace(/\s+\\\*\s+(?:ARABIC|ALPHABETIC|alphabetic|ROMAN|roman)\b/g,'').trim()+` \\* ${FORMAT[token.format]}`;
  const field=doc.createElementNS(NS.w,'w:fldSimple');field.setAttributeNS(NS.w,'w:instr',code);field.setAttributeNS(NS.w,'w:dirty','true');
  field.appendChild(textRun(previewNumberFormat('#E'+token.format,{equation:values[token.counter]})));return field;
 });
 return {p,start,end,nodes,replacements,numberText,instructions:fields.map(f=>({counter:f.counter,code:f.code})),unchanged:object.layout.numberFormat===pattern};
}

async function settingsInfo(document){
 const relPart=document.mainPart.replace(/([^/]+)$/,'_rels/$1.rels'),entry=document.zip.file(relPart);
 const rels=entry?parseDocxXml(await entry.async('string')):parseDocxXml(`<Relationships xmlns="${NS.rels}"/>`);
 const matches=Array.from(rels.getElementsByTagNameNS(NS.rels,'Relationship')).filter(n=>n.getAttribute('Type')===NS.r+'/settings');
 if(matches.length>1||matches[0]?.getAttribute('TargetMode')==='External')throw Error('Ambiguous DOCX settings relationship');
 const path=matches.length?resolveDocxPart(matches[0].getAttribute('Target'),document.mainPart):posix.join(posix.dirname(document.mainPart),'settings.xml');
 if(matches.length&&!document.zip.file(path)||!matches.length&&document.zip.file(path))throw Error('DOCX settings relationship does not match its part');
 const doc=document.zip.file(path)?parseDocxXml(await document.zip.file(path).async('string')):parseDocxXml(`<w:settings xmlns:w="${NS.w}"/>`);
 const nodes=descendants(doc,'docVar').filter(n=>n.getAttributeNS(NS.w,'name')===DEFAULT);
 if(nodes.length>1)throw Error('Duplicate document numbering defaults');
 return {path,doc,node:nodes[0]??null,relPart,rels,related:matches.length>0};
}
function normalizeOptions(value,count){
 keys(value,['scope','index','indices','numberFormat','updateFuture'],'numbering options');
 if(!['current','selected','all','future'].includes(value.scope))throw Error('Invalid numbering scope');tokens(value.numberFormat);
 if(value.updateFuture!==undefined&&typeof value.updateFuture!=='boolean')throw Error('Invalid updateFuture flag');
 let indices=[];
 if(value.scope==='current'){
  if(value.indices!==undefined)throw Error('Current scope accepts index only');indices=[value.index];
 }else if(value.scope==='selected'){
  if(value.index!==undefined||!Array.isArray(value.indices)||!value.indices.length)throw Error('Selected scope requires indices');indices=value.indices;
 }else if(value.index!==undefined||value.indices!==undefined)throw Error('This scope does not accept explicit indices');
 else if(value.scope==='all')indices=Array.from({length:count},(_,i)=>i);
 if(indices.length>500||new Set(indices).size!==indices.length||indices.some(i=>!Number.isSafeInteger(i)||i<0||i>=count))throw Error('Invalid or duplicate numbering indices');
 const options={scope:value.scope,numberFormat:value.numberFormat,updateFuture:value.scope==='future'||value.updateFuture===true};
 if(value.scope==='current')options.index=value.index;
 if(value.scope==='selected')options.indices=[...indices].sort((a,b)=>a-b);
 return {options,indices:[...indices].sort((a,b)=>a-b)};
}
async function makePlan(bytes,options){
 const document=await inspectDocx(bytes),selection=normalizeOptions(options,document.objects.length),normalized=selection.options,settings=await settingsInfo(document);
 if(Object.keys(document.zip.files).some(path=>/^_xmlsignatures\//.test(path)))throw Error('Signed documents cannot be changed by the copy engine');
 if(descendants(settings.doc,'documentProtection').some(node=>node.getAttributeNS(NS.w,'enforcement')&&!['false','0','off'].includes(node.getAttributeNS(NS.w,'enforcement'))))throw Error('Protected documents require a Word host operation');
 const bookmarkNames=new Map(),bookmarkIDs=new Map();
 for(const doc of new Set(document.objects.map(o=>o.partDoc)))for(const bookmark of descendants(doc,'bookmarkStart')){
  const name=bookmark.getAttributeNS(NS.w,'name').toLowerCase(),id=bookmark.getAttributeNS(NS.w,'id');bookmarkNames.set(name,(bookmarkNames.get(name)??0)+1);
  let ids=bookmarkIDs.get(doc);if(!ids){ids=new Map();bookmarkIDs.set(doc,ids);}ids.set(id,(ids.get(id)??0)+1);
 }
 const prepared=new Map(),targets=[];
 for(const index of selection.indices){
  const object=document.objects[index],target={index,part:object.part,nativeSha256:object.nativeSha256??null,bookmarkName:object.layout?.bookmarkName??null,beforeFormat:object.layout?.numberFormat??null,beforeNumber:object.layout?.numberText??null,afterNumber:null,status:'skipped',reason:null};
  try{
   if(object.layout?.bookmarkName&&bookmarkNames.get(object.layout.bookmarkName.toLowerCase())!==1)throw Error('Duplicate numbering bookmarks require Word');
   const change=prepare(object,normalized.numberFormat);
   if(bookmarkIDs.get(object.partDoc)?.get(change.start.getAttributeNS(NS.w,'id'))!==1)throw Error('Duplicate numbering bookmark identities require Word');
   target.afterNumber=change.numberText;target.status=change.unchanged?'unchanged':'ready';target.counterInstructions=change.instructions;if(!change.unchanged)prepared.set(index,change);
  }
  catch(error){target.reason=error.message;}
  targets.push(target);
 }
 const documentDefaultChanged=normalized.updateFuture&&(settings.node?.getAttributeNS(NS.w,'val')!==normalized.numberFormat||document.numberFormat!==normalized.numberFormat);
 const plan={schema:PLAN,sourceSha256:hash(bytes),options:normalized,targets,documentDefaultChanged,summary:{selected:targets.length,ready:targets.filter(t=>t.status==='ready').length,unchanged:targets.filter(t=>t.status==='unchanged').length,skipped:targets.filter(t=>t.status==='skipped').length},requiresWordFieldUpdate:prepared.size>0,limits:{existingNumbers:'bounded-equationlab-or-shared-bookmarks',liveWordMutation:false,hostVerified:false}};
 plan.planSha256=hash(stable(plan));return {plan,document,prepared,settings};
}
/** Read-only, deterministic plan for the exact source bytes. */
