enum InterfaceLanguage: String, CaseIterable, Identifiable {
    case system, simplifiedChinese = "zh-Hans", english = "en"
    var id: String { rawValue }
    var usesEnglish: Bool {
        switch self {
        case .english: true
        case .simplifiedChinese: false
        case .system: !(Locale.preferredLanguages.first ?? "en").hasPrefix("zh")
        }
    }
    var locale: Locale { Locale(identifier: usesEnglish ? "en" : "zh-Hans") }
    var shortLabel: String { usesEnglish ? "EN" : "中文" }
    @MainActor func localizeStandardMenu(_ menu: NSMenu) {
        let titles = ["File":"文件", "Edit":"编辑", "View":"显示", "Window":"窗口", "Help":"帮助",
                      "Undo":"撤销", "Redo":"重做", "Cut":"剪切", "Copy":"复制", "Paste":"粘贴", "Select All":"全选",
                      "Minimize":"最小化", "Zoom":"缩放", "Bring All to Front":"前置全部窗口", "Close Window":"关闭窗口",
                      "Show Sidebar":"显示边栏", "Hide Sidebar":"隐藏边栏", "Enter Full Screen":"进入全屏幕", "Exit Full Screen":"退出全屏幕",
                      "Services":"服务", "Hide EquationLab":"隐藏 EquationLab", "Hide Others":"隐藏其他", "Show All":"全部显示",
                      "Quit EquationLab":"退出 EquationLab", "About EquationLab":"关于 EquationLab"]
        for item in menu.items {
            if let pair = titles.first(where: { $0.key == item.title || $0.value == item.title }) {
                item.title = usesEnglish ? pair.key : pair.value
            }
            if let submenu = item.submenu { localizeStandardMenu(submenu) }
        }
    }
    func text(_ source: String) -> String {
        guard usesEnglish else { return source }
        if let value = Self.englishStrings[source] { return value }
        if source.hasPrefix("定义"), source.hasSuffix("样式…") { return "Define " + text(String(source.dropFirst(2).dropLast(3))) + " style…" }
        for suffix in ["数值", "单位"] where source.hasSuffix(suffix) { return text(String(source.dropLast(suffix.count))) + " " + (suffix == "数值" ? "value" : "unit") }
        for (prefix, translated) in Self.prefixes where source.hasPrefix(prefix) {
            return translated + text(String(source.dropFirst(prefix.count)))
        }
        if source.hasPrefix("全部 "), source.hasSuffix(" 类字体") { return "All " + String(source.dropFirst(3).dropLast(4)) + " font roles" }
        return source
    }
