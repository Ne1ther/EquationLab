import test from 'node:test';import assert from 'node:assert/strict';
import JSZip from 'jszip';
import {createDocx,flatOpc,fromFlatOpc,editDocx,inspectDocx} from '../src/document.mjs';
import {compareSelection} from '../src/selection.mjs';

test('Selection guard tolerates the identifiers regenerated by Mac Word exports',async()=>{
 const source=await createDocx([{latex:'x^{3}'}]),zip=await JSZip.loadAsync(source);
 let doc=await zip.file('word/document.xml').async('string');doc=doc.replace('<w:p>','<w:p w:rsidR="12345678" w:rsidRDefault="12345678" xmlns:w14="http://schemas.microsoft.com/office/word/2010/wordml" w14:paraId="12345678">').replace('ObjectID="_1700000001"','ObjectID="_1987654321"');zip.file('word/document.xml',doc);
 zip.file('word/settings.xml',(await zip.file('word/settings.xml').async('string')).replace('</w:settings>','<w:rsids><w:rsid w:val="12345678"/></w:rsids></w:settings>'));
 assert.equal((await compareSelection(await flatOpc(source),await flatOpc(await zip.generateAsync({type:'nodebuffer'})))).equal,true);
});

test('Selection guard rejects native edits and image replacements',async()=>{
 const source=await createDocx([{latex:'x^{3}'}]),info=await inspectDocx(source),digit=info.objects[0].characters.find(c=>c.char==='3');
 const edited=await editDocx(source,0,{[digit.offset]:'4'});
 assert.equal((await compareSelection(await flatOpc(source),await flatOpc(edited))).equal,false);
 const zip=await JSZip.loadAsync(source);zip.file('word/media/image1.png',Buffer.from('changed image'));
 assert.equal((await compareSelection(await flatOpc(source),await flatOpc(await zip.generateAsync({type:'nodebuffer'})))).equal,false);
});

test('Selection guard rejects changed prose, formatting and object relationships',async()=>{
 const source=await createDocx([{latex:'x^{3}'}]),original=await flatOpc(source);
 for(const [part,from,to]of [['word/document.xml','Formula 1','Changed prose'],['word/document.xml','<w:position','<w:b/><w:position'],['word/_rels/document.xml.rels','embeddings/oleObject1.bin','embeddings/other.bin']]){
  const zip=await JSZip.loadAsync(source);zip.file(part,(await zip.file(part).async('string')).replace(from,to));
  assert.equal((await compareSelection(original,await flatOpc(await zip.generateAsync({type:'nodebuffer'})))).equal,false);
 }
});

test('Flat OPC preserves Word part content types across editing exports',async()=>{
 const zip=await JSZip.loadAsync(await createDocx([{latex:'x^{3}'}]));
 const contentType='application/vnd.openxmlformats-officedocument.theme+xml';
 zip.file('[Content_Types].xml',(await zip.file('[Content_Types].xml').async('string')).replace('</Types>',`<Override PartName="/word/theme/theme1.xml" ContentType="${contentType}"/></Types>`));
 zip.file('word/theme/theme1.xml','<a:theme xmlns:a="http://schemas.openxmlformats.org/drawingml/2006/main" name="Host theme"/>');
 const xml=await flatOpc(await zip.generateAsync({type:'nodebuffer'}));
 assert.ok(xml.includes(`pkg:name="/word/theme/theme1.xml" pkg:contentType="${contentType}"`));
 const imported=await fromFlatOpc(xml),info=await inspectDocx(imported),digit=info.objects[0].characters.find(c=>c.char==='3');
 const edited=await flatOpc(await editDocx(imported,0,{[digit.offset]:'4'}));
 assert.ok(edited.includes('pkg:name="/word/embeddings/nativeBridge1.bin" pkg:contentType="application/vnd.openxmlformats-officedocument.oleObject"'));
});
